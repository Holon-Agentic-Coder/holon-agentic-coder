from __future__ import annotations

from pathlib import Path

import pytest

from scripts.check_module_budgets import ALLOW_CHANGE_ENV, FILESYSTEM_NOTICE, main
from tests.flow.test_module_budgets import BASE_CONFIG, PACKAGE, _lines, _module, _repo, _run, _write_config

GENERATED = {"path": f"{PACKAGE}/generated.py", "reason": "generated by protoc"}


@pytest.fixture(autouse=True)
def _no_authorisation(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.delenv(ALLOW_CHANGE_ENV, raising=False)


@pytest.mark.parametrize(
    "module", ["apps/app/src/newpkg/mod.py", "apps/newapp/src/newpkg/mod.py", "scripts/new/mod.py"]
)
def test_a_module_in_a_new_package_over_the_default_fails_without_a_configuration_change(
    tmp_path: Path, capsys: pytest.CaptureFixture[str], module: str
):
    config = _repo(tmp_path)
    _module(tmp_path, module, 11)
    assert _run(tmp_path, config) == 1
    assert f"{module}: 11 lines exceeds its limit of 10" in _lines(capsys, "::error::")[0]


def test_an_init_module_over_the_default_fails(tmp_path: Path, capsys: pytest.CaptureFixture[str]):
    config = _repo(tmp_path)
    _module(tmp_path, f"{PACKAGE}/__init__.py", 11)
    assert _run(tmp_path, config) == 1
    assert f"{PACKAGE}/__init__.py: 11 lines exceeds its limit of 10" in _lines(capsys, "::error::")[0]


def test_a_frozen_module_grown_by_one_line_past_its_override_fails(tmp_path: Path, capsys: pytest.CaptureFixture[str]):
    config = _repo(tmp_path)
    _module(tmp_path, f"{PACKAGE}/big.py", 20)
    assert _run(tmp_path, config) == 0
    capsys.readouterr()
    _module(tmp_path, f"{PACKAGE}/big.py", 21)
    assert _run(tmp_path, config) == 1
    assert f"{PACKAGE}/big.py: 21 lines exceeds its limit of 20" in _lines(capsys, "::error::")[0]


def test_a_frozen_module_shrunk_below_its_override_passes_with_a_ratchet_down_notice(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
):
    config = _repo(tmp_path)
    assert _run(tmp_path, config) == 0
    out = capsys.readouterr().out
    assert f"::notice::module budget: lower the override of {PACKAGE}/big.py from 20 to 15" in out
    assert "::error::" not in out


def test_a_frozen_module_shrunk_within_the_default_gets_a_notice_to_remove_its_override(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
):
    config = _repo(tmp_path)
    _module(tmp_path, f"{PACKAGE}/big.py", 7)
    assert _run(tmp_path, config) == 0
    assert any(f"remove the override of {PACKAGE}/big.py (20)" in line for line in _lines(capsys, "::notice::"))


def test_a_module_at_its_override_gets_no_notice(tmp_path: Path, capsys: pytest.CaptureFixture[str]):
    config = _repo(tmp_path)
    _module(tmp_path, f"{PACKAGE}/big.py", 20)
    assert _run(tmp_path, config) == 0
    assert _lines(capsys, "::notice::") == []


@pytest.mark.parametrize(
    "entry",
    [GENERATED, {"path": f"{PACKAGE}/vendor/", "reason": "vendored from upstream 1.2"}],
    ids=["file", "directory"],
)
def test_an_excluded_path_is_skipped_even_over_the_default(
    tmp_path: Path, capsys: pytest.CaptureFixture[str], entry: dict
):
    _repo(tmp_path)
    _module(tmp_path, f"{PACKAGE}/generated.py", 50)
    _module(tmp_path, f"{PACKAGE}/vendor/lib.py", 50)
    _module(tmp_path, f"{PACKAGE}/vendor/__init__.py", 50)
    other = f"{PACKAGE}/vendor/lib.py" if entry is GENERATED else f"{PACKAGE}/generated.py"
    config = _write_config(tmp_path / "custom.json", {**BASE_CONFIG, "exclude": [entry]})
    assert _run(tmp_path, config) == 1
    errors = _lines(capsys, "::error::")
    assert all(entry["path"] not in error for error in errors)
    assert any(other in error for error in errors)


def test_only_the_named_exclusions_are_skipped(tmp_path: Path, capsys: pytest.CaptureFixture[str]):
    _repo(tmp_path)
    _module(tmp_path, f"{PACKAGE}/generated.py", 50)
    config = _write_config(tmp_path / "custom.json", {**BASE_CONFIG, "exclude": [GENERATED]})
    assert _run(tmp_path, config) == 0
    assert "Module budgets passed: 2 modules (default 10, 1 overrides, 1 excluded)" in capsys.readouterr().out


@pytest.mark.parametrize(
    "entry",
    [{"path": f"{PACKAGE}/generated.py"}, {**GENERATED, "reason": "  "}, {**GENERATED, "reason": None}],
    ids=["missing-reason", "blank-reason", "null-reason"],
)
def test_an_exclude_entry_without_a_reason_fails(tmp_path: Path, capsys: pytest.CaptureFixture[str], entry: dict):
    _repo(tmp_path)
    config = _write_config(tmp_path / "custom.json", {**BASE_CONFIG, "exclude": [entry]})
    assert _run(tmp_path, config) == 1
    errors = _lines(capsys, "::error::module budget configuration")
    assert len(errors) == 1
    assert "exclude entry 0" in errors[0]


def test_untracked_test_and_non_python_files_are_not_measured(tmp_path: Path, capsys: pytest.CaptureFixture[str]):
    config = _repo(tmp_path)
    _module(tmp_path, "apps/app/tests/test_big.py", 50)
    _module(tmp_path, f"{PACKAGE}/data.txt", 50)
    _module(tmp_path, "docs/example.py", 50)
    _module(tmp_path, "apps/app/src.py", 50)
    assert _run(tmp_path, config) == 0
    _module(tmp_path, f"{PACKAGE}/untracked.py", 50)
    assert main(["--root", str(tmp_path), "--config", str(config), "--base", "none"]) == 0
    assert "Module budgets passed: 2 modules" in capsys.readouterr().out


def test_a_tracked_module_deleted_from_disk_is_skipped(tmp_path: Path, capsys: pytest.CaptureFixture[str]):
    config = _repo(tmp_path)
    _module(tmp_path, f"{PACKAGE}/gone.py", 50)
    assert _run(tmp_path, config) == 1
    capsys.readouterr()
    (tmp_path / PACKAGE / "gone.py").unlink()
    assert main(["--root", str(tmp_path), "--config", str(config), "--base", "none"]) == 0


def test_a_non_utf8_module_fails_naming_it(tmp_path: Path, capsys: pytest.CaptureFixture[str]):
    config = _repo(tmp_path)
    (tmp_path / PACKAGE / "latin1.py").write_bytes(b"x = '\xe9'\n")
    assert _run(tmp_path, config) == 1
    assert f"{PACKAGE}/latin1.py: cannot be read as UTF-8 text" in _lines(capsys, "::error::")[0]


def test_outside_a_git_repository_the_source_roots_are_walked_with_a_notice(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
):
    config = _repo(tmp_path)
    _module(tmp_path, "scripts/tool.py", 11)
    _module(tmp_path, "apps/app/tests/test_big.py", 50)
    assert main(["--root", str(tmp_path), "--config", str(config), "--base", "none"]) == 1
    out = capsys.readouterr().out
    assert f"::notice::module budget: {FILESYSTEM_NOTICE}" in out
    assert [line for line in out.splitlines() if line.startswith("::error::")] == [
        "::error::module budget: scripts/tool.py: 11 lines exceeds its limit of 10; split the module into smaller "
        "modules - the budget is frozen and may not be changed"
    ]


def test_a_change_to_exclude_is_frozen_unless_authorised(
    tmp_path: Path, capsys: pytest.CaptureFixture[str], monkeypatch: pytest.MonkeyPatch
):
    base = _repo(tmp_path)
    _module(tmp_path, f"{PACKAGE}/generated.py", 50)
    config = _write_config(tmp_path / "changed.json", {**BASE_CONFIG, "exclude": [GENERATED]})
    assert _run(tmp_path, config, base) == 1
    errors = _lines(capsys, "::error::")
    assert len(errors) == 1
    assert "exclude changed" in errors[0]
    assert "frozen" in errors[0]
    monkeypatch.setenv(ALLOW_CHANGE_ENV, "1")
    assert _run(tmp_path, config, base) == 0
