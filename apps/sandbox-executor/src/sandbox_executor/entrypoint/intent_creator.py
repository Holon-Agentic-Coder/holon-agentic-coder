#!/usr/bin/env python3
import json
import os
import subprocess
import sys
from datetime import UTC, datetime

from sandbox_executor.agent_runner import cleanup_repo_dir, get_repo_url, get_workspace_dir
from sandbox_executor.ledger import atomic_ledger_append
from sandbox_executor.redaction import redact_agent_secrets, redact_command


def run_cmd(
    args: list[str],
    cwd: str | None = None,
    env: dict[str, str] | None = None,
    check: bool = True,
) -> subprocess.CompletedProcess[str]:
    """Run a command, echoing it with credentials masked, and exit on failure when `check` is set.

    The echo and the failure diagnostics go through the shared redactors, because the clone URL and
    git's own error messages can carry the GitHub token.

    Args:
        args: The command and its arguments.
        cwd: Working directory for the command.
        env: Environment for the command; inherits the current environment when None.
        check: Exit the process with the command's return code if it fails.

    Returns:
        The CompletedProcess, whose stdout and stderr are raw and unredacted.
    """
    print(f"Running: {redact_command(args)}")
    result = subprocess.run(args, cwd=cwd, env=env, capture_output=True, text=True)
    if result.returncode != 0 and check:
        print(f"Command failed with code {result.returncode}")
        print(f"Stdout:\n{redact_agent_secrets(result.stdout)}")
        print(f"Stderr:\n{redact_agent_secrets(result.stderr)}")
        sys.exit(result.returncode)
    return result


def main():  # noqa: PLR0915
    intent_json_path = "/tmp/intent.json"
    if not os.path.exists(intent_json_path):
        print(f"Error: {intent_json_path} does not exist.")
        sys.exit(1)

    with open(intent_json_path) as f:
        intent_data = json.load(f)

    # Front-load clarifying questions validation (Bean 0085)
    from sandbox_executor.flow import validate_intent_questions

    valid_questions, unresolved = validate_intent_questions(intent_data)
    if not valid_questions:
        unresolved_list_str = "; ".join(unresolved)
        print(
            f"Error: Unresolved questions detected in intent payload. "
            f"All clarifying questions must be resolved prior to Stage 1 completion. Unresolved: {unresolved_list_str}",
            file=sys.stderr,
        )
        sys.exit(1)

    description = intent_data.get("description", "No description provided")
    goal = intent_data.get("goal", "No goal provided")
    slug = intent_data.get("slug", "")
    branch = intent_data.get("branch")

    if not branch:
        if not slug:
            print("Error: Either 'branch' or 'slug' must be provided in intent JSON.")
            sys.exit(1)
        import re

        # Convert any space to '-' and collapse consecutive hyphens
        slug_clean = slug.replace(" ", "-")
        slug_clean = re.sub(r"-+", "-", slug_clean)

        import time

        branch = f"I-{int(time.time())}-{slug_clean}"
        intent_data["branch"] = branch
        intent_data["slug"] = slug_clean

    intent_branch = f"{branch}/_"

    target_branch = intent_data.get("target_branch", "main")

    repo_dir = get_workspace_dir()
    cleanup_repo_dir(repo_dir, raise_on_error=True)
    os.makedirs(repo_dir, exist_ok=True)

    repo_url = get_repo_url()
    run_cmd(["git", "clone", "--branch", target_branch, "--single-branch", "--depth", "1", repo_url, "."], cwd=repo_dir)

    # Checkout intent branch
    run_cmd(["git", "checkout", "-B", intent_branch, f"origin/{target_branch}"], cwd=repo_dir)

    # Proactively check and resolve any stage conflicts
    from sandbox_executor.flow import check_and_resolve_stage_conflicts

    check_and_resolve_stage_conflicts(repo_dir=repo_dir, target_branch=target_branch, stage_name="intent")

    # Update intents.jsonl
    timestamp = datetime.now(UTC).strftime("%Y-%m-%dT%H:%M:%S.%f")[:-3] + "Z"
    intent_data["status"] = "proposed"
    intent_data["created_at"] = timestamp

    ledger_dir = os.path.join(repo_dir, "holon-knowledge/ledger")
    os.makedirs(ledger_dir, exist_ok=True)
    intents_file_path = os.path.join(ledger_dir, "intents.jsonl")

    with atomic_ledger_append(intents_file_path) as lf:
        lf.write(json.dumps(intent_data) + "\n")

    questions_summary = ""
    if intent_data.get("questions") or intent_data.get("answers") or intent_data.get("open_questions"):
        resolved_content = (
            intent_data.get("answers") or intent_data.get("questions") or intent_data.get("open_questions")
        )
        questions_summary = f"\n\nResolved Questions:\n{json.dumps(resolved_content, indent=2)}\n"

    commit_msg = (
        f"intent: created {intent_branch}\n\n"
        f"Description:\n{description}\n\n"
        f"Goal:\n{goal}\n"
        f"{questions_summary}\n"
        f"Generated by Holon Intent Agent at {datetime.now(UTC).strftime('%Y-%m-%dT%H:%M:%SZ')}\n"
    )

    # Git commit & push
    run_cmd(["git", "add", "holon-knowledge/ledger/intents.jsonl"], cwd=repo_dir)
    run_cmd(["git", "config", "--local", "user.email", "intent-agent@holon-agentic-coder.com"], cwd=repo_dir)
    run_cmd(["git", "config", "--local", "user.name", "Holon Intent Agent"], cwd=repo_dir)
    run_cmd(["git", "commit", "-m", commit_msg], cwd=repo_dir)
    run_cmd(["git", "push", "-u", "origin", intent_branch], cwd=repo_dir)

    print(f"Intent branch '{intent_branch}' created and intent logged.")


if __name__ == "__main__":
    main()
