from __future__ import annotations

import os
import subprocess
import sys
from pathlib import Path

import pytest

from scripts.check_commit_trailers import find_attribution_lines
from tests.test_workflow_triggers import parse_triggers

REPO_ROOT = Path(__file__).resolve().parents[3]
SCRIPT = REPO_ROOT / "scripts" / "check_commit_trailers.py"
HOOK = REPO_ROOT / ".githooks" / "commit-msg"
WORKFLOW = REPO_ROOT / ".github" / "workflows" / "test-commit-trailers.yml"
CO_AUTHOR = "Co-Authored-By: Claude <noreply@anthropic.com>"
CLAUDE_CODE_FOOTER = "Generated with [Claude Code](https://claude.com/claude-code)"
GIT_ENV = {
    **os.environ,
    "GIT_CONFIG_GLOBAL": os.devnull,
    "GIT_CONFIG_SYSTEM": os.devnull,
    "GIT_AUTHOR_NAME": "t",
    "GIT_AUTHOR_EMAIL": "t@example.com",
    "GIT_COMMITTER_NAME": "t",
    "GIT_COMMITTER_EMAIL": "t@example.com",
}


def run_script(*args: str, cwd: Path) -> subprocess.CompletedProcess[str]:
    return subprocess.run([sys.executable, str(SCRIPT), *args], capture_output=True, text=True, cwd=cwd, env=GIT_ENV)


def git(repo: Path, *args: str) -> str:
    return subprocess.run(
        ["git", "-C", str(repo), "-c", "commit.gpgsign=false", *args],
        capture_output=True,
        text=True,
        env=GIT_ENV,
        check=True,
    ).stdout.strip()


def commit(repo: Path, message: str) -> str:
    git(repo, "commit", "-q", "--allow-empty", "-m", message)
    return git(repo, "rev-parse", "HEAD")


@pytest.mark.parametrize(
    ("message", "offending_line"),
    [
        (f"feat: x\n\n{CO_AUTHOR}\n", CO_AUTHOR),
        (f"feat: x\n\n{CO_AUTHOR}\n".lower(), CO_AUTHOR.lower()),
        (f"feat: x\n\n{CLAUDE_CODE_FOOTER}\n", CLAUDE_CODE_FOOTER),
    ],
)
def test_message_file_with_attribution_fails_naming_the_line(tmp_path: Path, message: str, offending_line: str) -> None:
    message_file = tmp_path / "COMMIT_EDITMSG"
    message_file.write_text(message, encoding="utf-8")

    result = run_script("--message-file", str(message_file), cwd=tmp_path)

    assert result.returncode != 0
    assert offending_line in result.stderr


def test_message_file_with_flow_trailers_only_passes(tmp_path: Path) -> None:
    message_file = tmp_path / "COMMIT_EDITMSG"
    message_file.write_text("feat: x\n\nAction-Origin: pr_review\nReview-Iteration: 2\n", encoding="utf-8")

    result = run_script("--message-file", str(message_file), cwd=tmp_path)

    assert result.returncode == 0
    assert result.stderr == ""


def test_message_file_ignores_verbose_diff_below_scissors_line(tmp_path: Path) -> None:
    message_file = tmp_path / "COMMIT_EDITMSG"
    message_file.write_text(
        "feat: x\n\n"
        "# ------------------------ >8 ------------------------\n"
        "# Do not modify or remove the line above.\n"
        "diff --git a/notes.md b/notes.md\n"
        f" {CO_AUTHOR}\n",
        encoding="utf-8",
    )

    result = run_script("--message-file", str(message_file), cwd=tmp_path)

    assert result.returncode == 0
    assert result.stderr == ""


@pytest.mark.parametrize(
    "line",
    [
        f"   {CO_AUTHOR}",
        f"\N{ROBOT FACE} {CLAUDE_CODE_FOOTER}",
        "Co-Developed-By: Someone <s@example.com>",
        "Generated-By: a tool",
        "Assisted-By: an assistant",
    ],
)
def test_attribution_lines_are_found(line: str) -> None:
    assert find_attribution_lines(f"feat: x\n\n{line}") == [line]


@pytest.mark.parametrize(
    "line",
    [f"# {CO_AUTHOR}", f"#{CO_AUTHOR}", "Generated by Holon Intent Agent at 2026-11-27T00:08:37Z"],
)
def test_comment_and_flow_lines_are_not_attribution(line: str) -> None:
    assert find_attribution_lines(f"feat: x\n\n{line}") == []


def test_range_fails_naming_only_the_offending_commit(tmp_path: Path) -> None:
    git(tmp_path, "init", "-q", "-b", "main")
    root = commit(tmp_path, "chore: root")
    clean = commit(tmp_path, "feat: clean\n\nAction-Origin: pr_review")
    offending = commit(tmp_path, f"feat: offending\n\n{CO_AUTHOR}")

    over_both = run_script("--range", f"{root}..{offending}", cwd=tmp_path)
    over_clean = run_script("--range", f"{root}..{clean}", cwd=tmp_path)

    assert over_both.returncode != 0
    assert f"{git(tmp_path, 'rev-parse', '--short', offending)}: {CO_AUTHOR}" in over_both.stderr
    assert git(tmp_path, "rev-parse", "--short", clean) not in over_both.stderr
    assert over_clean.returncode == 0


def test_range_that_git_cannot_resolve_fails(tmp_path: Path) -> None:
    git(tmp_path, "init", "-q", "-b", "main")

    assert run_script("--range", "missing..HEAD", cwd=tmp_path).returncode == 2


def test_commit_msg_hook_runs_the_check_on_the_message_file() -> None:
    hook = HOOK.read_text(encoding="utf-8")

    assert os.access(HOOK, os.X_OK)
    assert "scripts/check_commit_trailers.py" in hook
    assert '--message-file "$1"' in hook


def test_workflow_checks_the_pull_request_commits_with_full_history() -> None:
    workflow = WORKFLOW.read_text(encoding="utf-8")

    assert "pull_request" in parse_triggers(workflow)
    assert "scripts/check_commit_trailers.py --range" in workflow
    assert "fetch-depth: 0" in workflow
    assert "${{ github.event.pull_request" not in workflow.split("run:", 1)[1]
